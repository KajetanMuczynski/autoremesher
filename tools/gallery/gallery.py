"""Rebuild the public before/after gallery (docs/gallery/) from the `gallery` set of corpus.json.

    python tools/gallery/gallery.py [--ref master] [--work DIR] [--replicates 4] [--only a,b]
                                    [--size 480] [--no-runs]

1. Runs the CLI of REF on every gallery entry through tools/bench/ab.py (`run REF --set gallery
   --only <id> --targets <target> --resolutions quality --replicates N [--cli-arg ...]`), so every
   number is an ab.py run that can be repeated. Replicate u0 is the plain input; u1..uN are the
   1-ulp inputs of the noise rule, used only for the "over N+1 inputs" columns.
2. Renders u0's input and output side by side with Blender's Workbench (bpy 5.2 from PyPI or
   Blender's Python, headless): flat grey, black wireframe, non-quad faces red. The input wire is
   left out when its edges would be under 4 pixels apart (a dense sculpt reads as a black blob).
3. Writes docs/gallery/img/<id>.webp and the generated table between the markers of
   docs/gallery/README.md; the panel rows come from the add-on's own report.py, so the numbers read
   as the panel shows them.

Needs bpy (Python 3.13), numpy, Pillow, and scipy + libigl for metrics.py; the meshes in <work>/meshes as ab.py expects them
(fetch_meshes.sh, make_sculpt.py --only sculpt_dyntopo, make_sculpt.py --set brush --only
brush_twist). Only public-license or procedural meshes belong in the gallery set: see
docs/gallery/README.md, "Sources and licenses".
"""
import argparse
import json
import os
import platform
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "tools", "bench"))
sys.path.insert(0, os.path.join(REPO, "addon", "quadami"))
import ab  # noqa: E402
import report as panel  # noqa: E402  (the add-on's report.py, no bpy in it)

DOCS = os.path.join(REPO, "docs", "gallery")
BEGIN, END = "<!-- gallery-table:begin (generated by tools/gallery/gallery.py) -->", "<!-- gallery-table:end -->"
GREY, RED, WIRE = (0.80, 0.80, 0.80, 1.0), (0.90, 0.15, 0.12, 1.0), (0.05, 0.05, 0.05, 1.0)


def entries(only):
    _, meshes = ab.load_set("gallery")
    return [m for m in meshes if not only or m["id"] in only.split(",")]


def run_entry(m, a):
    cmd = [sys.executable, os.path.join(REPO, "tools", "bench", "ab.py"), "run", a.ref, "--work", a.work,
           "--set", "gallery", "--only", m["id"], "--targets", str(m["target"]), "--resolutions", "quality",
           "--replicates", str(a.replicates), "--jobs", "1"]
    cmd += ["--cli-arg=" + x for x in m.get("cli_args", [])]
    subprocess.run(cmd, check=True)
    return os.path.join(ab.run_dir(a.ref, m.get("cli_args", []), a.work), "gallery", m["id"],
                        f"quality-t{m['target']}")


# ---- rendering (bpy imported lazily so --help works without it) ------------------------------

def load(bpy, path, up="Y"):
    """Imports an OBJ; up is the file's up axis (OBJ convention Y; procedural meshes are Z-up)."""
    before = set(bpy.data.objects)
    bpy.ops.wm.obj_import(filepath=path, use_split_objects=False, use_split_groups=False, up_axis=up,
                          forward_axis="NEGATIVE_Z" if up == "Y" else "Y")
    return [o for o in bpy.data.objects if o not in before and o.type == "MESH"][0]


def geometry(np, ob):
    me = ob.data
    co = np.empty(len(me.vertices) * 3)
    me.vertices.foreach_get("co", co)
    ev = np.empty(len(me.edges) * 2, int)
    me.edges.foreach_get("vertices", ev)
    # World coordinates: the importer may put its axis conversion on the object, not the vertices.
    mw = np.array(ob.matrix_world)
    co, ev = co.reshape(-1, 3) @ mw[:3, :3].T + mw[:3, 3], ev.reshape(-1, 2)
    return co, float(np.linalg.norm(co[ev[:, 0]] - co[ev[:, 1]], axis=1).mean())


def paint(np, ob, per_face):
    """Corner colour attribute: grey, non-quads red when per_face."""
    me = ob.data
    sizes = np.empty(len(me.polygons), int)
    me.polygons.foreach_get("loop_total", sizes)
    face_col = np.where((sizes != 4)[:, None] & per_face, RED, GREY)
    attr = me.color_attributes.new("c", "FLOAT_COLOR", "CORNER")
    attr.data.foreach_set("color", np.repeat(face_col, sizes, axis=0).ravel())
    me.color_attributes.active_color = attr


def tile(path, up, frame, view, size, out_png, wire, quads):
    import bpy
    import numpy as np
    from mathutils import Vector
    bpy.ops.wm.read_factory_settings(use_empty=True)
    sc = bpy.context.scene
    ob = load(bpy, path, up)
    _, h = geometry(np, ob)
    paint(np, ob, quads)
    if wire:
        # Workbench does not render the overlay wireframe, so the wire is geometry.
        w = ob.copy()
        w.data = ob.data.copy()
        sc.collection.objects.link(w)
        mod = w.modifiers.new("w", "WIREFRAME")
        mod.thickness = 0.06 * h
        mod.use_even_offset = False
        mod.use_relative_offset = False
        w.data.color_attributes.remove(w.data.color_attributes["c"])
        black = w.data.color_attributes.new("c", "FLOAT_COLOR", "POINT")
        black.data.foreach_set("color", np.tile(WIRE, len(w.data.vertices)))
        w.data.color_attributes.active_color = black
    sc.render.engine = "BLENDER_WORKBENCH"
    sc.display.shading.light = "STUDIO"
    sc.display.shading.color_type = "VERTEX"
    sc.render.resolution_x = sc.render.resolution_y = size
    sc.render.film_transparent = True  # composited onto white in render_entry
    cam = bpy.data.cameras.new("c")
    cam.type = "ORTHO"
    cam.ortho_scale = frame["scale"]
    cam.clip_end = frame["scale"] * 10
    co = bpy.data.objects.new("c", cam)
    sc.collection.objects.link(co)
    sc.camera = co
    d = Vector(view).normalized()
    co.location = Vector(frame["center"]) + d * frame["scale"] * 3
    co.rotation_euler = (-d).to_track_quat("-Z", "Y").to_euler()
    sc.render.filepath = out_png
    bpy.ops.render.render(write_still=True)


def render_entry(m, src, out_obj, rep, size, img_path, tmp):
    import bpy
    import numpy as np
    from mathutils import Vector
    from PIL import Image, ImageDraw, ImageFont
    up, view = m.get("up", "Y"), m.get("view", [1, -1, 0.5])
    # Frame by the input (a lost part should show as missing on the right), fitted to its extent on
    # the image plane of the camera that tile() sets up.
    bpy.ops.wm.read_factory_settings(use_empty=True)
    ob_in = load(bpy, src, up)
    co_in, h_in = geometry(np, ob_in)
    tris = len(ob_in.data.polygons)
    rot = (-Vector(view).normalized()).to_track_quat("-Z", "Y").to_matrix()
    axes = np.array([list(rot.col[0]), list(rot.col[1])])
    lo, hi = (co_in @ axes.T).min(0), (co_in @ axes.T).max(0)
    centre = co_in.mean(0)
    centre = centre - axes.T @ (axes @ centre) + axes.T @ ((lo + hi) / 2)
    frame = {"center": centre.tolist(), "scale": float((hi - lo).max()) * 1.06}
    wire_in = h_in / (frame["scale"] / size) >= 4.0
    a, b = os.path.join(tmp, "in.png"), os.path.join(tmp, "out.png")
    tile(src, up, frame, view, size, a, wire_in, False)
    tile(out_obj, up, frame, view, size, b, True, True)
    o = rep.get("output", {})
    labels = [f"Input: {tris:,} faces" + ("" if wire_in else " (wire too dense to draw)"),
              f"Quadami: {o.get('quads', 0):,} quads, {o.get('non_quads', 0)} non-quads (red)"]
    pad, band = 8, 30
    sheet = Image.new("RGB", (2 * size + pad, size + band), "white")
    draw = ImageDraw.Draw(sheet)
    try:
        font = ImageFont.truetype("DejaVuSans.ttf", 15)
    except OSError:
        font = ImageFont.load_default()
    for i, (png, text) in enumerate(zip((a, b), labels)):
        rgba = Image.open(png).convert("RGBA")
        sheet.paste(rgba, (i * (size + pad), 0), rgba)
        draw.text((i * (size + pad) + 8, size + 6), text, fill="black", font=font)
    sheet.save(img_path, "WEBP", quality=80, method=6)


# ---- table ----------------------------------------------------------------------------------

def slug(title):
    """GitHub's anchor for a heading."""
    return re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")


def rows_of(rep):
    return {label: (value, problem) for label, value, problem in panel.summary_rows(rep)}


def spread(reports, get, fmt="{:,}"):
    vals = [v for v in (get(r) for r in reports if r.get("status") == "ok") if v is not None]
    if not vals:
        return "-"
    lo, hi = fmt.format(min(vals)), fmt.format(max(vals))
    return lo if lo == hi else f"{lo}-{hi}"


def shape_error(r):
    """99th percentile of the input-to-output distance in % of the input's bounding-box diagonal:
    large when a part of the input has no output near it (a thin part lost or shrunk)."""
    m = r.get("metrics") or {}
    return 100.0 * m["distance"]["in_to_out_p99"] / m["diag"] if "distance" in m else None


def table(results, a, commit):
    n = a.replicates + 1
    out = [BEGIN, "",
           f"Generated from `{a.ref}` = `{commit[:7]}` by `tools/gallery/gallery.py`, Quality resolution, "
           f"default settings unless noted, on {platform.machine()} with {os.cpu_count()} cores "
           f"(time is wall time of the plain input there; a laptop differs). Columns after the bar: "
           f"range over the plain input and {a.replicates} inputs moved by one float32 ulp, as "
           f"Blender hands them over (the noise rule in tools/bench/README.md). Shape error: 99th "
           f"percentile of the distance from the input to the output, in % of the input's diagonal "
           f"(tools/bench/metrics.py; the panel does not show it).", "",
           f"| Mesh | Target | Quads | Non-quads | Folded faces | Holes | Time | Quads over {n} | "
           f"Non-quads over {n} | Folded over {n} | Holes over {n} | Shape error over {n} |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for m, reps in results:
        r0 = rows_of(reps[0])
        o = reps[0].get("output", {})
        holes = reps[0].get("islands", {}).get("holes", 0) if r0.get("Holes") else "n/a (open)"
        out.append(
            f"| [{m['title']}](#{slug(m['title'])}) | {m['target']:,} | {o.get('quads', 0):,} | "
            f"{o.get('non_quads', 0)} | {o.get('folded_faces', 0)} | {holes} | {r0['Time'][0]} | "
            f"{spread(reps, lambda r: r['output']['quads'])} | {spread(reps, lambda r: r['output']['non_quads'])} | "
            f"{spread(reps, lambda r: r['output']['folded_faces'])} | "
            f"{spread(reps, lambda r: r.get('islands', {}).get('holes', 0))} | "
            f"{spread(reps, shape_error, '{:.1f} %')} |")
    out.append("")
    for m, reps in results:
        out += [f"### {m['title']}", "",
                f"![{m['title']}: input left, Quadami output right](img/{m['id']}.webp)", ""]
        rows = rows_of(reps[0])
        flagged = [f"{k}: {v}" for k, (v, p) in rows.items() if p]
        out.append("Panel rows flagged: " + ("; ".join(flagged) if flagged else "none") + ".")
        warnings = [t for t, first, _ in panel.warning_lines(reps[0], 10_000)]
        if warnings:
            out.append("")
            out += [f"> Panel: {t}" for t in warnings]
        out.append("")
    out.append(END)
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--ref", default="master")
    ap.add_argument("--work", default=os.environ.get("AR_WORK", os.path.expanduser("~/ar-work")))
    ap.add_argument("--replicates", type=int, default=4)
    ap.add_argument("--only")
    ap.add_argument("--size", type=int, default=480, help="pixels per tile (each image is two tiles)")
    ap.add_argument("--no-runs", action="store_true", help="render and tabulate finished runs only")
    a = ap.parse_args()
    commit = ab.git("rev-parse", a.ref)
    os.makedirs(os.path.join(DOCS, "img"), exist_ok=True)
    results = []
    import tempfile
    for m in entries(a.only):
        d = (os.path.join(ab.run_dir(a.ref, m.get("cli_args", []), a.work), "gallery", m["id"],
                          f"quality-t{m['target']}") if a.no_runs else run_entry(m, a))
        reps = []
        for k in range(a.replicates + 1):
            r = json.load(open(os.path.join(d, f"u{k}", "report.json")))
            r["metrics"] = json.load(open(os.path.join(d, f"u{k}", "record.json"))).get("metrics")
            reps.append(r)
        with tempfile.TemporaryDirectory() as tmp:
            render_entry(m, os.path.join(a.work, "meshes", m["file"]), os.path.join(d, "u0", "out.obj"),
                         reps[0], a.size, os.path.join(DOCS, "img", m["id"] + ".webp"), tmp)
        results.append((m, reps))
    if a.only:
        print("--only: images written, table left unchanged (it needs every entry)")
        return
    page = os.path.join(DOCS, "README.md")
    text = open(page).read()
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    text = head + table(results, a, commit) + tail
    with open(page, "w") as fp:
        fp.write(text)
    print("wrote", page)


if __name__ == "__main__":
    main()
